#!/usr/bin/env python3
"""Semi-automatic ground-truth labelling for real footage.

Propagates a single hand-placed seed box through a clip and writes ground truth
in the schema ``make_test_video.py`` produces, so ``tools/eval_real.py`` can
score real video.

Uses normalised cross-correlation rather than the system's own tracker: ground
truth generated by the thing under test is circular. Every run also writes a
verification contact sheet, which must be checked - see docs/FINDINGS.md.

Usage::

    python tools/label_real.py --source video/test3.mp4 \\
        --start 5250 --frames 500 --seed 590,186,58,84 --global-search \\
        --out output/test3_groundtruth.json
"""

from __future__ import annotations

import argparse
import json
import os
import sys

import cv2
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from src.utils.video import VideoSource  # noqa: E402


def _clip_box(x: int, y: int, w: int, h: int, shape: tuple[int, int]) -> tuple[int, int, int, int]:
    H, W = shape
    x = int(np.clip(x, 0, max(0, W - 1)))
    y = int(np.clip(y, 0, max(0, H - 1)))
    w = int(np.clip(w, 1, W - x))
    h = int(np.clip(h, 1, H - y))
    return x, y, w, h


def track_ncc(
    source: str,
    start: int,
    frames: int,
    seed: tuple[int, int, int, int],
    process_width: int,
    search_pad: float,
    template_alpha: float,
    min_score: float,
    update_score: float,
    global_search: bool,
) -> tuple[list[dict], list[tuple[int, np.ndarray, tuple[int, int, int, int] | None]]]:
    """Propagate ``seed`` forward with NCC matching.

    ``min_score`` decides whether a frame gets a label at all; ``update_score``
    decides whether the template may learn from it. The second threshold is the
    anti-drift lock: adapting on every frame lets the template walk onto
    background and report confident, entirely wrong labels.
    """
    src = VideoSource(source, process_width=process_width, start_frame=start, max_frames=frames)

    x, y, w, h = seed
    template: np.ndarray | None = None
    prev_center: np.ndarray | None = None
    velocity = np.zeros(2, dtype=np.float32)

    labelled: list[dict] = []
    preview: list[tuple[int, np.ndarray, tuple[int, int, int, int] | None]] = []

    for index, frame in src:
        gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
        H, W = gray.shape

        if template is None:
            x, y, w, h = _clip_box(x, y, w, h, (H, W))
            template = gray[y : y + h, x : x + w].astype(np.float32)
            box: tuple[int, int, int, int] | None = (x, y, w, h)
            prev_center = np.array([x + w / 2.0, y + h / 2.0], dtype=np.float32)
        else:
            if global_search:
                sx, sy = 0, 0
                window = gray.astype(np.float32)
            else:
                pred = prev_center + velocity
                pad_x = int(max(24, search_pad * w))
                pad_y = int(max(24, search_pad * h))
                sx = int(np.clip(pred[0] - w / 2.0 - pad_x, 0, W - 1))
                sy = int(np.clip(pred[1] - h / 2.0 - pad_y, 0, H - 1))
                sx2 = int(np.clip(pred[0] + w / 2.0 + pad_x, sx + w + 1, W))
                sy2 = int(np.clip(pred[1] + h / 2.0 + pad_y, sy + h + 1, H))
                window = gray[sy:sy2, sx:sx2].astype(np.float32)

            if window.shape[0] < h or window.shape[1] < w:
                box = None
            else:
                response = cv2.matchTemplate(window, template, cv2.TM_CCOEFF_NORMED)
                _, score, _, loc = cv2.minMaxLoc(response)
                if score < min_score:
                    box = None
                else:
                    nx, ny = sx + loc[0], sy + loc[1]
                    box = _clip_box(nx, ny, w, h, (H, W))
                    center = np.array([nx + w / 2.0, ny + h / 2.0], dtype=np.float32)
                    velocity = 0.6 * velocity + 0.4 * (center - prev_center)
                    prev_center = center
                    patch = gray[ny : ny + h, nx : nx + w].astype(np.float32)
                    if patch.shape == template.shape and score >= update_score:
                        template = (1.0 - template_alpha) * template + template_alpha * patch

        objects: list[dict] = []
        if box is not None:
            bx, by, bw, bh = box
            objects.append(
                {
                    "class": "drone",
                    "bbox": [float(bx), float(by), float(bx + bw), float(by + bh)],
                    "size_px": float(max(bw, bh)),
                }
            )
        labelled.append({"frame": int(index), "objects": objects})
        preview.append((int(index), frame, box))

    src.release()
    return labelled, preview


def write_check_sheet(
    preview: list[tuple[int, np.ndarray, tuple[int, int, int, int] | None]],
    path: str,
    tiles: int = 12,
) -> None:
    """Render a grid of labelled frames so the result can be eyeballed."""
    if not preview:
        return
    picks = np.linspace(0, len(preview) - 1, min(tiles, len(preview))).astype(int)
    imgs = []
    for p in picks:
        index, frame, box = preview[p]
        img = frame.copy()
        if box is not None:
            bx, by, bw, bh = box
            cv2.rectangle(img, (bx, by), (bx + bw, by + bh), (0, 255, 0), 2)
        else:
            cv2.putText(img, "NO LABEL", (10, 60), cv2.FONT_HERSHEY_SIMPLEX, 1.0, (0, 0, 255), 2)
        cv2.putText(img, str(index), (10, 28), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (0, 255, 255), 2)
        imgs.append(cv2.resize(img, (480, 270)))
    cols = 3
    rows = [np.hstack(imgs[r : r + cols]) for r in range(0, len(imgs) - len(imgs) % cols, cols)]
    if rows:
        os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)
        cv2.imwrite(path, np.vstack(rows), [cv2.IMWRITE_JPEG_QUALITY, 85])


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", required=True)
    ap.add_argument("--start", type=int, default=0)
    ap.add_argument("--frames", type=int, default=600)
    ap.add_argument("--seed", required=True, help="x,y,w,h of the target in the START frame")
    ap.add_argument("--out", required=True)
    ap.add_argument("--process-width", type=int, default=1280,
                    help="must match video.process_width, or boxes land in the wrong space")
    ap.add_argument("--search-pad", type=float, default=1.6)
    ap.add_argument("--template-alpha", type=float, default=0.10)
    ap.add_argument("--min-score", type=float, default=0.35,
                    help="NCC below this emits no label rather than a guessed box")
    ap.add_argument("--update-score", type=float, default=0.55,
                    help="NCC below this leaves the template untouched (anti-drift)")
    ap.add_argument("--global-search", action="store_true",
                    help="search the whole frame; cannot lose the target out of the window")
    args = ap.parse_args()

    seed = tuple(int(v) for v in args.seed.split(","))
    if len(seed) != 4:
        ap.error("--seed needs x,y,w,h")

    labelled, preview = track_ncc(
        args.source, args.start, args.frames, seed,  # type: ignore[arg-type]
        args.process_width, args.search_pad, args.template_alpha, args.min_score,
        args.update_score, args.global_search,
    )

    n_lab = sum(1 for f in labelled if f["objects"])
    meta = {
        "source": args.source,
        "method": "ncc-template-propagation",
        "seed": list(seed),
        "start_frame": args.start,
        "process_width": args.process_width,
        "frames_labelled": n_lab,
        "frames_total": len(labelled),
        "frames_data": labelled,
    }
    os.makedirs(os.path.dirname(os.path.abspath(args.out)) or ".", exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        json.dump(meta, fh, indent=1)

    check = os.path.splitext(args.out)[0] + "_check.jpg"
    write_check_sheet(preview, check)
    print(f"labelled {n_lab}/{len(labelled)} frames -> {args.out}")
    print(f"VERIFY THIS BEFORE USING IT: {check}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
